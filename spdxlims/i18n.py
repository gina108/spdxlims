def set_language(language_code: str | None) -> None:
    global _current_language
    codes = {code for code, _label in SUPPORTED_LANGUAGES}
    _current_language = language_code if language_code in codes else "en"


def get_language() -> str:
    return _current_language


def tr(text: str, **kwargs: str) -> str:
    translated = _TRANSLATIONS.get(_current_language, {}).get(text, text)
    if kwargs:
        return translated.format(**kwargs)
    return translated
